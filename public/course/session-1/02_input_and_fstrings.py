"""جلسهٔ ۱ — input و f-string: گرفتن ورودی و چسباندن مقدار داخل متن."""

# ==== ۱. input همیشه متن برمی‌گرداند =================================
city = input("City: ")
pm25_text = input("PM2.5 (ug/m3): ")

print(type(pm25_text))          # <class 'str'>  ← حتی اگر کاربر عدد بزند

pm25 = float(pm25_text)          # تا تبدیل نکنید، جمع نمی‌شود
print(city, pm25, type(pm25))

# خطای کلاسیک هفتهٔ اول:
# int("48.3")  →  ValueError: invalid literal for int() with base 10: '48.3'
# int اعشار نمی‌پذیرد؛ برای اعشار از float استفاده کنید.

# ==== ۲. f-string ====================================================
print(f"{city}: PM2.5 = {pm25:.1f} ug/m3")     # یک رقم اعشار
print(f"{city}: PM2.5 = {pm25:.0f} ug/m3")     # گرد شده، بدون اعشار
print(f"{city!r} — طول متن شهر: {len(city)}")

# محاسبه داخل آکولاد هم مجاز است:
limit = 75
print(f"{city} is {'above' if pm25 > limit else 'below'} the limit")

# ==== ۳. ورودی عددی امن ==============================================
