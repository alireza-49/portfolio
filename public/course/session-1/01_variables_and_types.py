"""جلسهٔ ۱ — متغیر، نام‌گذاری و چهار نوع مقدار: str، int، float، bool."""

# ==== ۱. متغیر =======================================================
city = "Tehran"
pm25 = 48.3
n_stations = 12
is_valid = True

print(city, pm25, n_stations, is_valid)

# type() ابزار بازرسی است: می‌گوید مقدار از چه نوعی است.
print(type(city), type(pm25), type(n_stations), type(is_valid))
# <class 'str'> <class 'float'> <class 'int'> <class 'bool'>

# ==== ۲. نام خوب، نیمی از خوانایی ====================================
# بد: a = 48.3
# خوب: pm25_tehran = 48.3
pm25_tehran = 48.3
print("Tehran PM2.5:", pm25_tehran)

# ==== ۳. حساب ========================================================
a = 10
b = 4
print(a + b, a - b, a * b)   # 14 6 40
print(a / b)                 # 2.5  ← تقسیم همیشه اعشاری است
print(a // b)                # 2    ← تقسیم صحیح
print(a % b)                 # 2    ← باقی‌مانده
print(a ** b)                # 10000 ← توان

pm25_mg = pm25 / 1000
print("pm25 in mg/m3:", pm25_mg)

# ==== ۴. تبدیل نوع ===================================================
print(int("42") + 1)        # 43  ← متن عددی به عدد
print(str(75) + " ug/m3")   # 75 ug/m3 ← عدد به متن، چسباندن
print(int(3.99))            # 3   ← برش، نه گرد کردن

# ==== ۵. دقت اعشاری ==================================================
print(0.1 + 0.2)            # 0.30000000000000004
# کامپیوتر اعشار را دقیق نگه نمی‌دارد؛ برای پول از عدد صحیح (ریال) استفاده کنید.

