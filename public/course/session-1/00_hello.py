# ==== ۲. متن در برابر محاسبه =========================================
# هر چیزی داخل "" متن است؛ هر چیزی بیرونش کد.
print("2 + 3 =", 2 + 3)   # 2 + 3 = 5
print("2 + 3")            # 2 + 3  ← این یکی متن است، نه محاسبه

# ==== ۳. یک خطا را عمداً بسازید ======================================
