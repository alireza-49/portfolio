# print("2 + 3 = 2 + 3)
#   SyntaxError: '(' was never closed
#
# بعد از خواندن خطا، دوباره کامنتش کنید.

# ==== تمرین ==========================================================
# ۱) یک خط چاپ اضافه کنید که اسم خودتان را چاپ کند.
# ۲) با print ثابت کنید 10 / 4 برابر 2.5 است و 10 // 4 برابر 2.
